# Clean y-axis tick labels
def fmt_time(x, _):
    if x < 1:
        return f'{x:.1f}s'
    elif x < 60:
        return f'{x:.0f}s'
    elif x < 3600:
        return f'{x/60:.0f}m'
    else:
        return f'{x/3600:.1f}h'

