# ── Compute per-model averages ──────────────────────────────────────────────
bacc_lists = {m: [] for m in MODELS}
time_lists = {m: [] for m in MODELS}

for dataset, p_data in data.items():
    if dataset not in include_datasets:
        continue
    for p, values in p_data.items():
        for i, (bacc, time) in enumerate(values):
            if bacc is not None and time is not None:
                bacc_lists[MODELS[i]].append(bacc)
                time_lists[MODELS[i]].append(time)

avg_bacc = {m: np.mean(bacc_lists[m]) for m in MODELS}
avg_time = {m: np.mean(time_lists[m]) for m in MODELS}

# Print summary for inspection
print("Model          Avg BAcc (%)   Avg Time (s)")
print("-" * 45)
for m in MODELS:
    print(f"{m:<14} {avg_bacc[m]:>10.2f}   {avg_time[m]:>12.1f}")

# ── Pareto frontier (maximise BAcc, minimise Time) ──────────────────────────
def pareto_frontier(models, bacc, time):
    frontier = []
    for m in models:
        dominated = any(
            bacc[o] >= bacc[m] and time[o] <= time[m] and (bacc[o] > bacc[m] or time[o] < time[m])
            for o in models if o != m
        )
        if not dominated:
            frontier.append(m)
    return sorted(frontier, key=lambda m: bacc[m])

pareto = pareto_frontier(MODELS, avg_bacc, avg_time)
print("\nPareto-efficient models:", pareto)

